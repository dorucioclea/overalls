# Run with: mix run --no-start scripts/extract_documentation.exs
# This deterministic source extraction does not invent translated prose.
root = Path.expand("..", __DIR__)
paths = Path.wildcard(Path.join(root, "priv/docs/*.md")) |> Enum.sort()

messages =
  paths
  |> Enum.flat_map(fn path ->
    path
    |> File.read!()
    |> Marshall.LocalizedMarkdown.units()
    |> Enum.filter(& &1.translatable?)
    |> Enum.map(& &1.source)
  end)
  |> Kernel.++([
    "Overalls documentation",
    "Browser extension",
    "Getting started",
    "Command reference",
    "Automation",
    "Reflection integration",
    "Push notifications",
    "Options:"
  ])
  |> Kernel.++(Enum.map(OverallsProtocol.SSHCommand.catalog(), & &1.summary))
  |> Enum.uniq()
  |> Enum.sort()

body =
  Enum.map_join(messages, ",\n", fn message ->
    "    dgettext_noop(\"documentation\", " <>
      inspect(message, limit: :infinity, printable_limit: :infinity) <> ")"
  end)

source = """
defmodule Marshall.DocumentationMessages do
  @moduledoc "Generated by scripts/extract_documentation.exs; English sources remain authoritative."
  use Gettext, backend: MarshallWeb.Gettext
  @messages [
#{body}
  ]
  @spec messages() :: [String.t()]
  def messages, do: @messages
end
"""

source = source |> Code.format_string!() |> IO.iodata_to_binary() |> Kernel.<>("\n")
target = Path.join(root, "lib/marshall/documentation_messages.ex")

case System.argv() do
  [] ->
    File.write!(target, source)

  ["--check"] ->
    if File.read!(target) != source, do: raise("documentation message extraction is stale")

  _ ->
    raise("usage: mix run --no-start scripts/extract_documentation.exs [--check]")
end

IO.puts("Extracted #{length(messages)} documentation messages")
