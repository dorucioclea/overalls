// The Windows runner's notification text (ADR-0235), generated from the app's
// ARB catalogs so native code shows exactly the strings Dart would. Only the
// fixed `pushNeedsInputTitle` and `pushNeedsInputBody` messages are native:
// a notification never shows text from a deployment.
import 'dart:convert';

/// The ARB message ids the runner needs, as the darwin `.lproj` and Android
/// `values-*` resources carry them.
const String titleKey = 'pushNeedsInputTitle';
const String bodyKey = 'pushNeedsInputBody';

/// The header path inside the repository.
const String headerPath = 'mila/app/windows/runner/strings.g.h';

/// The fixed notification text for one locale.
final class NotificationText {
  const NotificationText({required this.locale, required this.title, required this.body});

  /// A BCP 47 tag, e.g. `pt-BR` or `zh-Hans`.
  final String locale;
  final String title;
  final String body;
}

/// A catalog that cannot supply the notification text.
final class CatalogError implements Exception {
  const CatalogError(this.message);
  final String message;

  @override
  String toString() => message;
}

/// `app_pt_BR.arb` -> `pt-BR`, or null for any other file name.
String? localeOf(String fileName) {
  final match = RegExp(r'^app_([a-z]{2,3}(?:_[A-Za-z0-9]{2,8})*)\.arb$').firstMatch(fileName);
  return match?.group(1)!.replaceAll('_', '-');
}

/// The notification text of one ARB catalog, validated as JSON objects with
/// string messages. A catalog without either message is refused: the
/// runner's fallback is English, not a missing string.
NotificationText readCatalog(String locale, String contents) {
  final Object? decoded;
  try {
    decoded = jsonDecode(contents);
  } on FormatException {
    throw CatalogError('$locale: not JSON');
  }
  if (decoded is! Map<String, Object?>) throw CatalogError('$locale: not a JSON object');
  final Map<String, Object?> catalog = decoded;
  String message(String key) {
    final value = catalog[key];
    if (value is! String || value.trim().isEmpty) throw CatalogError('$locale: no $key string');
    if (value.contains('{')) throw CatalogError('$locale: $key has a placeholder');
    return value;
  }

  return NotificationText(locale: locale, title: message(titleKey), body: message(bodyKey));
}

/// A wide string literal: printable ASCII as is, everything else as a
/// universal character name, so the header is ASCII and needs no source
/// encoding flag.
String wideLiteral(String text) {
  final out = StringBuffer('L"');
  for (final rune in text.runes) {
    if (rune == 0x22 || rune == 0x5c) {
      out.write('\\${String.fromCharCode(rune)}');
    } else if (rune >= 0x20 && rune < 0x7f) {
      out.writeCharCode(rune);
    } else if (rune <= 0xffff) {
      out.write('\\u${rune.toRadixString(16).padLeft(4, '0')}');
    } else {
      out.write('\\U${rune.toRadixString(16).padLeft(8, '0')}');
    }
  }
  out.write('"');
  return out.toString();
}

/// The complete header for [texts], sorted by locale so the output is stable.
String renderHeader(List<NotificationText> texts) {
  final sorted = [...texts]..sort((a, b) => a.locale.compareTo(b.locale));
  if (!sorted.any((t) => t.locale == 'en')) throw const CatalogError('no English catalog');
  final rows = [
    for (final t in sorted)
      '    {${wideLiteral(t.locale)}, ${wideLiteral(t.title)}, ${wideLiteral(t.body)}},',
  ];
  return '''
// Generated by `mila/tool/bin/native_strings.dart` from
// mila/localization/catalogs/app_*.arb ($titleKey, $bodyKey). Do not edit; run
// `dart run bin/native_strings.dart` in mila/tool, and `--check` in CI.
#pragma once

namespace mila_strings {

struct NotificationText {
  const wchar_t* locale;  // BCP 47
  const wchar_t* title;
  const wchar_t* body;
};

inline constexpr NotificationText kNotificationTexts[] = {
${rows.join('\n')}
};

}  // namespace mila_strings
''';
}
